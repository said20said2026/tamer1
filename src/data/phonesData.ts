export const PHONES_DATA: Phone[] = RAW_PHONES_DATA.map((phone) => {
  const usedOffers = USED_OFFERS_BY_PHONE[phone.id] || [];
  const refurbs = usedOffers.filter((o) => o.condition === 'refurbished');
  const used = usedOffers.filter((o) => o.condition === 'used');

  const lowestRefurbishedPriceSAR = refurbs.length > 0 ? Math.min(...refurbs.map((o) => o.priceSAR)) : undefined;
  const lowestUsedPriceSAR = used.length > 0 ? Math.min(...used.map((o) => o.priceSAR)) : undefined;

  // Calculate lowest price across ALL offers (both local and global)
  const allOfferPrices = phone.offers.map((o) => o.priceSAR);
  const lowestPriceSAR = allOfferPrices.length > 0 ? Math.min(...allOfferPrices) : phone.lowestPriceSAR;

  return {
    ...phone,
    lowestPriceSAR,
    usedOffers,
    hasRefurbished: refurbs.length > 0,
    hasUsed: used.length > 0,
    lowestRefurbishedPriceSAR,
    lowestUsedPriceSAR,
  };
});

